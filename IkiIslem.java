public class IkiIslem {
    public static void main(String[] args) {
        int a = 17;
        int b = 5;
        System.out.println(a + " + " + b + " = " + (a + b));
        System.out.println(a + " - " + b + " = " + (a - b));
        System.out.println(a + " * " + b + " = " + (a * b));
        System.out.println(a + " / " + b + " = " + (a / b));
        System.out.println(a + " % " + b + " = " + (a % b));
        
        System.out.println();
         int yeniA = 17;
        double yeniB = 5.0; 
        System.out.println("--- DOUBLE (Ondalıklı Sayı) İLE İŞLEMLER ---");
        System.out.println(yeniA + " + " + yeniB + " = " + (yeniA + yeniB));
        System.out.println(yeniA + " - " + yeniB + " = " + (yeniA - yeniB));
        System.out.println(yeniA + " * " + yeniB + " = " + (yeniA * yeniB));
        System.out.println(yeniA + " / " + yeniB + " = " + (yeniA / yeniB)); 
        System.out.println(yeniA + " % " + yeniB + " = " + (yeniA % yeniB));
        
        //[SAYIN HOCAMA NOT]:int'i kullandığımız zaman sonuç daima tam sayıyı vermektedir fakat double'yi kullandığımız zamanda sonuç daima ondalıklı sayı vermektedir.
    
}
    
}