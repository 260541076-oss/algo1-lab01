public class CarpimTablosu {
    public static void main(String[] args) {
for (int i = 10; i >= 1; i--) {
            int sonuc = 5 * i;
            System.out.println("5 x " + i + " = " + sonuc);
        }

        // [SAYIN HOCAMA NOT]: Döngü başlangıcını 10 yaptık, i >= 1 şartını koyduk ve i-- ile geriye sardık.
        // ve böylece başlangıç,ilerleme yönü ve durma şartını döngüde değiştirmiş olduk.
    }
}
